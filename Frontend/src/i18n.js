export function getUiText(language) {
  return UI_TEXT[language] || UI_TEXT.tr
}

export function getInitialLanguage() {
  if (typeof window === 'undefined') return 'tr'

  try {
    const savedLanguage = window.localStorage.getItem(STORAGE_KEY)
    if (UI_TEXT[savedLanguage]) return savedLanguage
  } catch {
    // localStorage can be unavailable in private browsing modes.
  }

  return window.navigator?.language?.toLowerCase().startsWith('tr') ? 'tr' : 'en'
}

export function saveLanguage(language) {
  if (typeof window === 'undefined') return

  try {
    window.localStorage.setItem(STORAGE_KEY, language)
  } catch {
    // Persisting the language is a convenience, not a requirement.
  }
}

export function getOptionLabel(options, id, t) {
  const option = options.find(item => item.id === id)
  if (!option) return id
  if (option.labelKey) return t.options[option.labelKey] || option.labelKey
  return option.label || id
}

export function getSlotLabel(index, t) {
  return `${t.app?.slot || 'Slot'} ${String.fromCharCode(65 + index)}`
}
